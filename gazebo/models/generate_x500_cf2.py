#!/usr/bin/env python3
"""
x500_cf2 — x500의 비행 물리에 Crazyflie 2 외형을 씌운 모델 생성기.

측위계(지상 LiDAR)가 보는 것은 기체의 visual 형상뿐이므로, 소형 기체를 시험할 때는
겉모양만 바꾸면 된다. 비행은 PX4 x500 그대로라 기존 offboard 스크립트·튜닝을 쓴다.
(가속·자세 응답은 x500이다 — 실제 Crazyflie의 운동 특성이 아님)

PX4의 x500_base/x500 model.sdf를 읽어서
  - 모든 link의 visual/collision을 지우고
  - base_link에 Crazyflie 메시(SCALE배)와 그 외곽 크기의 충돌 박스를 넣고
  - x500의 모터·제어 플러그인을 그대로 붙인다.
관성·센서·조인트는 x500과 같다. PX4 쪽 x500이 바뀌면 이 스크립트만 다시 돌리면 된다.

메시: bitcraze/crazyflie-simulation (MIT) 의 cf2_assembly_with_props.dae.
      원점이 기체 바닥면, 단위 m, 외곽 96.3 x 99.8 x 27.2 mm (프롭 포함).

실행:
  python3 generate_x500_cf2.py            # SCALE 기본값
  CF2_SCALE=2 python3 generate_x500_cf2.py   # → x500_cf2x2
  cp -r x500_cf2 ~/drone_project/PX4-Autopilot/Tools/simulation/gz/models/
  PX4_GZ_WORLD=indoor_cage make px4_sitl gz_x500_cf2
배율 1이 아닌 모델은 PX4 airframe(예: 4023_gz_x500_cf2x2)도 따로 등록해야 한다.
"""

import os
import shutil
import xml.etree.ElementTree as ET

MODELS_DIR = os.path.dirname(os.path.abspath(__file__))
PX4_MODELS = os.path.expanduser(
    os.environ.get("PX4_GZ_MODELS",
                   "~/drone_project/PX4-Autopilot/Tools/simulation/gz/models"))
# 외형 배율. 1 = 실제 Crazyflie 2 (메시 축 방향 약 10 cm, 가드 끝~끝 실측 14 cm).
# 1.3 = Tello 크기: 두 기체를 같은 방법(프로펠러 가드 끝~끝)으로 잰 14 cm, 18 cm 의 비 (2026-11-09).
# 2 는 예전에 Tello 급으로 쓰던 값인데 실제 Tello 보다 크다 (길이 약 1.5배).
# 배율마다 모델을 따로 만든다: x500_cf2 (1), x500_cf2x1p3 (1.3), x500_cf2x2 (2) …
# 높이 배율 (기본 = SCALE). Tello 크기 모델은 CF2_SCALE=1.3 CF2_SCALE_Z=1.5:
# 메시 높이 27.2 mm x 1.5 = 41 mm = Tello 공식 높이.
SCALE = float(os.environ.get("CF2_SCALE", "1"))
SCALE_Z = float(os.environ.get("CF2_SCALE_Z", SCALE))
_tag = lambda v: f"{v:g}".replace(".", "p")
MODEL_NAME = ("x500_cf2" if SCALE == 1 else f"x500_cf2x{_tag(SCALE)}") + ("" if SCALE_Z == SCALE else f"z{_tag(SCALE_Z)}")

MESH = "cf2_assembly_with_props.dae"
# 메시 외곽 (배율 1, base_link 기준) — 변환까지 적용해 잰 값
MESH_MIN = (-0.0481, -0.0499, 0.0013)
MESH_MAX = (0.0481, 0.0499, 0.0285)

# 스폰 높이: 충돌 박스 바닥이 지면 바로 위에 오도록 약간 띄워서 떨어뜨린다.
SPAWN_Z = 0.03


def _strip_shapes(model):
    for link in model.findall("link"):
        for tag in ("visual", "collision"):
            for el in link.findall(tag):
                link.remove(el)


def _sub(parent, tag, text=None):
    el = ET.SubElement(parent, tag)
    if text is not None:
        el.text = text
    return el


def _add_cf2_shapes(base_link):
    s, sz = SCALE, SCALE_Z
    # visual: Crazyflie 메시
    vis = ET.Element("visual", name="cf2_visual")
    geo = _sub(vis, "geometry")
    mesh = _sub(geo, "mesh")
    _sub(mesh, "scale", f"{s} {s} {sz}")
    _sub(mesh, "uri", f"model://{MODEL_NAME}/meshes/{MESH}")

    # collision: 메시 외곽 박스 (착지용)
    size = [(hi - lo) * k for lo, hi, k in zip(MESH_MIN, MESH_MAX, (s, s, sz))]
    cz = (MESH_MIN[2] + MESH_MAX[2]) / 2.0 * sz
    col = ET.Element("collision", name="cf2_collision")
    _sub(col, "pose", f"0 0 {cz:.5f} 0 0 0")
    box = _sub(_sub(col, "geometry"), "box")
    _sub(box, "size", " ".join(f"{v:.5f}" for v in size))
    ode = _sub(_sub(_sub(col, "surface"), "contact"), "ode")
    _sub(ode, "min_depth", "0.001")
    _sub(ode, "max_vel", "0")

    # inertial 뒤, sensor 앞에 넣어 원래 순서를 흉내 낸다
    idx = next((i for i, el in enumerate(base_link) if el.tag == "sensor"),
               len(base_link))
    base_link.insert(idx, col)
    base_link.insert(idx, vis)
    return size


def main():
    base = ET.parse(os.path.join(PX4_MODELS, "x500_base", "model.sdf")).getroot()
    x500 = ET.parse(os.path.join(PX4_MODELS, "x500", "model.sdf")).getroot()

    model = base.find("model")
    model.set("name", MODEL_NAME)
    model.find("pose").text = f"0 0 {SPAWN_Z} 0 0 0"

    _strip_shapes(model)
    size = _add_cf2_shapes(model.find("link[@name='base_link']"))

    for plugin in x500.find("model").findall("plugin"):
        model.append(plugin)

    out_dir = os.path.join(MODELS_DIR, MODEL_NAME)
    mesh_dir = os.path.join(out_dir, "meshes")
    if not os.path.isdir(mesh_dir):     # 메시는 배율 1 모델 폴더에서 복사
        shutil.copytree(os.path.join(MODELS_DIR, "x500_cf2", "meshes"), mesh_dir)
    ET.indent(base, space="  ")
    ET.ElementTree(base).write(os.path.join(out_dir, "model.sdf"),
                               encoding="UTF-8", xml_declaration=True)

    with open(os.path.join(out_dir, "model.config"), "w") as f:
        f.write(f'''<?xml version="1.0"?>
<model>
  <name>{MODEL_NAME}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>
    x500 flight dynamics with a Crazyflie 2 appearance (scale {SCALE:g}, height {SCALE_Z:g}).
    Generated by gazebo/models/generate_x500_cf2.py.
    Mesh: bitcraze/crazyflie-simulation, MIT License, Copyright (c) 2022 Bitcraze.
  </description>
</model>
''')
    print(f"{MODEL_NAME} 생성: 배율 {SCALE:g} (높이 {SCALE_Z:g}), 외곽 "
          f"{size[0] * 100:.1f} x {size[1] * 100:.1f} x {size[2] * 100:.1f} cm")


if __name__ == "__main__":
    main()
